import { defineConfig } from "oxlint";
import antiSlop from "ultracite/oxlint/anti-slop";
import core from "ultracite/oxlint/core";
import { jsPluginSettings, selectJsPlugins } from "ultracite/oxlint/js-plugins";
import react from "ultracite/oxlint/react";
import tanstack from "ultracite/oxlint/tanstack";
import vitest from "ultracite/oxlint/vitest";

// The template's lint (Ultracite: Oxlint, type-aware), with its presets in
// its order, so the template's code lints as it did there (the TanStack
// preset relaxes some core rules, such as sort-keys). Left out: the shadcn
// preset and the TanStack and react-doctor plugins, which need the UI's
// packages; the chat UI's lint comes with the UI.
const jsPlugins = selectJsPlugins(["jsdoc-js", "sonarjs", "tsdoc", "github"]);

export default defineConfig({
  env: core.env,
  extends: [antiSlop, core, react, tanstack, vitest, jsPlugins],
  ignorePatterns: [
    ...(core.ignorePatterns ?? []),
    "**/.agents",
    "**/.claude",
    "dist",
    // Generated by paraglide (npm run generate-i18n).
    "src/paraglide",
    // Vendored from the eval-skills toolkit (setup_workspace.py); update it by
    // reinstalling, not editing.
    ".eval/*/scripts",
    ".eval/*/review-app",
  ],
  jsPlugins: [...jsPlugins.jsPlugins],
  options: { typeAware: true },
  settings: jsPluginSettings,
  rules: {
    // Effect's error factories (Schema.TaggedError<Self>()("Tag", {...})) are
    // calls whose name ends in "Error"; the rule reads them as `throw Error()`.
    "unicorn/throw-new-error": "off",
    // Both read Effect's data-first calls as array and Promise methods:
    // Effect.forEach(items, f) as forEach(callback, thisArg), and
    // Effect.catch as a promise's .catch. Effect's own
    // diagnostics (the type-check, tsconfig.json) ask for exactly these forms.
    "unicorn/no-array-method-this-argument": "off",
    "promise/prefer-await-to-then": "off",
    // Validation is Effect Schema; zod stays installed only as the AI SDK's
    // required peer dependency.
    "no-restricted-imports": [
      "error",
      {
        paths: [
          {
            name: "zod",
            message: 'Use Schema from "effect" (see GUIDE.md, Effect).',
          },
        ],
      },
    ],
  },
  overrides: [
    {
      // Tests assert through @effect/vitest's assert and named helpers, not
      // only expect. An override on the vitest preset's own files, with its
      // plugin, since the preset sets this rule in one.
      files: [
        "**/*.{test,spec,test-d,spec-d}.{ts,tsx,js,jsx,mts,cts,mjs,cjs}",
        "**/__tests__/**/*.{ts,tsx,js,jsx,mts,cts,mjs,cjs}",
      ],
      plugins: ["vitest"],
      rules: {
        "vitest/expect-expect": [
          "error",
          {
            // Exact names: `*` matches one segment of a dotted path
            // (assert.*), not the rest of a name.
            assertFunctionNames: ["expect", "assert", "assert.*"],
          },
        ],
      },
    },
  ],
});
