/* Explicitly invoked DEV-only synthetic smoke. Does not boot Nest, schedule jobs or call AI. */
const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const assert = require('node:assert/strict');
const { randomUUID, createHash } = require('node:crypto');
require('dotenv').config({ path: path.join(__dirname, '../.env'), override: true });
require('reflect-metadata');
require('ts-node').register({ transpileOnly: true, project: path.join(__dirname, '../tsconfig.json') });
require('tsconfig-paths').register({ baseUrl: path.join(__dirname, '..'), paths: { 'src/*': ['src/*'] } });
const { DataSource } = require('typeorm');
const { Logger } = require('@nestjs/common');
Logger.overrideLogger(false);
const { Business } = require('../src/business/business.entity');
const { ImportedDocument } = require('../src/document-import/entities/imported-document.entity');
const { ExtractedDocument } = require('../src/documents/extracted-document.entity');
const { ProtectedPdfStore } = require('../src/protected-pdf/protected-pdf.store');
const { PdfInspectionService } = require('../src/protected-pdf/pdf-inspection.service');
const { ProtectedPdfService } = require('../src/protected-pdf/protected-pdf.service');
const { GoogleDriveService } = require('../src/google-drive/google-drive.service');
const { DocumentImportSource } = require('../src/document-import/enums/document-import.enums');
const names = ['protected_documents', 'document_replacement_operations', 'protected_pdf_import_runs'];
const mode = process.argv[2];
let phase = 'preflight';
(async () => {
  assert(['--apply-schema', '--synthetic-test'].includes(mode), 'Explicit mode required');
  assert.equal(process.env.DB_DATABASE, 'keepintax-dev', 'DEV database required');
  assert.equal(process.env.COMPOSIO_ENVIRONMENT, 'dev', 'DEV Composio required');
  assert.equal(process.env.PROTECTED_PDF_DISPATCH_ENABLED, 'false', 'Automatic delivery must stay off');
  const ds = new DataSource({ type: 'mysql', host: process.env.DB_HOST, port: Number(process.env.DB_PORT), username: process.env.DB_USERNAME, password: process.env.DB_PASSWORD, database: process.env.DB_DATABASE, entities: [Business, ImportedDocument, ExtractedDocument], synchronize: false, migrationsRun: false, logging: false });
  await ds.initialize();
  try {
    assert.equal((await ds.query('SELECT DATABASE() AS name'))[0].name, 'keepintax-dev');
    const business = await ds.getRepository(Business).findOneBy({ id: 5 });
    assert.equal(business?.businessName, 'נגרות', 'Expected previously selected business 5');
    assert(business.firebaseId && business.businessNumber && business.driveFolderId && business.driveInboxFolderId, 'Business folders and owner required');
    const existing = await ds.query('SELECT TABLE_NAME FROM information_schema.TABLES WHERE TABLE_SCHEMA=DATABASE() AND TABLE_NAME IN (?,?,?)', names);
    if (mode === '--apply-schema') {
      phase = 'schema';
      assert.equal(existing.length, 0, 'Refuse partial or existing schema; inspect before retry');
      const sql = fs.readFileSync(path.join(__dirname, '../../docs/features/protected-pdf.sql'), 'utf8');
      const statements = sql.replace(/^\s*--.*$/gm, '').split(';').map(x => x.trim()).filter(Boolean);
      assert.equal(statements.length, 3);
      for (let i = 0; i < 3; i++) {
        assert(statements[i].startsWith(`CREATE TABLE ${names[i]} (`), 'Only approved CREATE TABLE statements');
        await ds.query(statements[i]);
        console.log(JSON.stringify({ phase, created: names[i] }));
      }
      const tables = await ds.query('SELECT TABLE_NAME,ENGINE FROM information_schema.TABLES WHERE TABLE_SCHEMA=DATABASE() AND TABLE_NAME IN (?,?,?)', names);
      assert.equal(tables.length, 3); assert(tables.every(t => t.ENGINE === 'InnoDB'));
      console.log(JSON.stringify({ phase, verifiedTables: tables.length, schemaSha256: createHash('sha256').update(sql).digest('hex') }));
      return;
    }
    assert.equal(existing.length, 3, 'Approved schema must already exist');
    assert.equal(process.env.PROTECTED_PDF_ENABLED, 'true', 'Feature must be explicitly enabled');
    const run = randomUUID();
    const evidencePath = path.join(os.tmpdir(), `keepintax-protected-pdf-${run}.json`);
    const evidence = { run, database: 'keepintax-dev', businessId: 5, noNestBoot: true, noAi: true, dispatchEnabled: false };
    const checkpoint = () => fs.writeFileSync(evidencePath, JSON.stringify(evidence, null, 2));
    checkpoint(); console.log(JSON.stringify({ evidencePath }));
    const fixture = name => Buffer.concat([fs.readFileSync(path.join(__dirname, '../test/fixtures/protected-pdf', name)), Buffer.from(`\n% KEEPINTAX-DEV-SYNTHETIC-${run}\n`)]);
    const locked = fixture('password-required-aes256.pdf'); const open = fixture('open.pdf');
    const inspector = new PdfInspectionService();
    assert.equal((await inspector.inspect(locked)).kind, 'password_required');
    assert.equal((await inspector.inspect(open)).kind, 'readable');
    const store = new ProtectedPdfStore(ds); const drive = new GoogleDriveService();
    const service = new ProtectedPdfService(store, inspector, ds.getRepository(Business), ds.getRepository(ImportedDocument), ds.getRepository(ExtractedDocument), drive);
    const input = { firebaseId: business.firebaseId, businessNumber: business.businessNumber, source: DocumentImportSource.MANUAL_UPLOAD, filename: `KEEPINTAX-DEV-LOCKED-${run}.pdf`, content: locked, metadata: { syntheticTestRun: run } };
    phase = 'locked-intake';
    const intake = await service.storeLocked(input); assert(intake.passwordRequired);
    const roots = await ds.query('SELECT * FROM protected_documents WHERE original_import_id=? AND firebase_id=? AND business_number=?', [intake.importedDocumentId, business.firebaseId, business.businessNumber]);
    assert.equal(roots.length, 1); const root = roots[0]; assert.equal(root.status, 'PASSWORD_REQUIRED');
    Object.assign(evidence, { protectedDocumentId: root.id, originalImportId: intake.importedDocumentId, originalDriveFileId: intake.driveFileId }); checkpoint();
    const folders = await drive.ensureProtectedFolders(business.driveFolderId);
    assert.deepEqual(await drive.getFolderParents(intake.driveFileId), [folders.blocked]);
    const lockedItems = await service.decorateArchive(business.firebaseId, business.businessNumber, [{ id: -1, driveFileId: intake.driveFileId }], true);
    const projected = lockedItems.filter(x => x.protectedDocumentId === root.id);
    assert.equal(projected.length, 1); assert.equal(projected[0].status, 'PASSWORD_REQUIRED'); assert(projected[0].canUploadOpenCopy);
    phase = 'authorization-validation';
    const file = { buffer: open, originalname: `KEEPINTAX-DEV-OPEN-${run}.pdf`, mimetype: 'application/pdf' };
    const key = randomUUID();
    await assert.rejects(() => service.history('unrelated-synthetic-owner', business.businessNumber, root.id));
    await assert.rejects(() => service.replace(business.firebaseId, business.firebaseId, business.businessNumber, root.id, key, false, file));
    await assert.rejects(() => service.replace(business.firebaseId, business.firebaseId, business.businessNumber, root.id, key, true, { ...file, buffer: locked }));
    phase = 'open-replacement';
    const accepted = await service.replace(business.firebaseId, business.firebaseId, business.businessNumber, root.id, key, true, file);
    assert(accepted.accepted); evidence.accepted = accepted; checkpoint();
    const repeated = await service.replace(business.firebaseId, business.firebaseId, business.businessNumber, root.id, key, true, file);
    assert.equal(repeated.operationId, accepted.operationId);
    const history = await service.history(business.firebaseId, business.businessNumber, root.id);
    assert.equal(history.status, 'REPLACED'); assert.equal(history.operations.length, 1); assert.equal(history.originalImportId, intake.importedDocumentId); assert.equal(history.originalDriveFileId, intake.driveFileId);
    const op = await store.operation(accepted.operationId);
    assert.equal(op.status, 'PENDING'); assert.equal(op.processing_status, 'NOT_STARTED');
    assert.deepEqual(await drive.getFolderParents(op.candidate_drive_id), [folders.staging]);
    assert.equal((await inspector.inspect(await drive.downloadFile(intake.driveFileId))).kind, 'password_required');
    assert.deepEqual(await drive.downloadFile(op.candidate_drive_id), open);
    const candidate = await ds.getRepository(ImportedDocument).findOneBy({ id: op.replacement_import_id });
    assert.equal(candidate.firebaseId, business.firebaseId); assert.equal(candidate.businessNumber, business.businessNumber); assert.equal(candidate.source, DocumentImportSource.MANUAL_UPLOAD);
    assert.equal((await drive.findProtectedUploads(folders.staging, op.id)).length, 1);
    const items = await service.decorateArchive(business.firebaseId, business.businessNumber, [{ id: -1, driveFileId: intake.driveFileId }, { id: -2, driveFileId: op.candidate_drive_id, status: 'PENDING' }], true);
    assert.equal(items.filter(x => x.protectedDocumentId === root.id).length, 1); assert(!items.some(x => x.driveFileId === intake.driveFileId));
    const extracted = await ds.query('SELECT COUNT(*) AS count FROM extracted_document WHERE drive_file_id IN (?,?) AND business_number=?', [intake.driveFileId, op.candidate_drive_id, business.businessNumber]);
    assert.equal(Number(extracted[0].count), 0, 'No AI processing expected');
    Object.assign(evidence, { completed: true, replacementImportId: candidate.id, replacementDriveFileId: op.candidate_drive_id, uploadStatus: op.status, processingStatus: op.processing_status, originalRetained: true, singleLogicalItem: true, idempotencyVerified: true, authorizationVerified: true }); checkpoint();
    console.log(JSON.stringify(evidence));
  } finally { await ds.destroy(); }
})().catch(error => { console.error(JSON.stringify({ failedPhase: phase, code: error.code || error.name, assertion: error.code === 'ERR_ASSERTION' ? error.message : undefined })); process.exitCode = 1; });
